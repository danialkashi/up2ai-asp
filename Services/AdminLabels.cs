        Sections.TryGetValue(key, out var m) ? m : new SectionMeta(key, "");

    /// <summary>کلید بخش‌های یک گروه، به ترتیب تعریف در <see cref="Sections"/>.</summary>
    public static IEnumerable<string> SectionsInGroup(string group, IEnumerable<string> available) =>
        Sections.Where(p => p.Value.Group == group)
                .Select(p => p.Key)
                .Where(available.Contains);

