namespace Up2Ai.Services;

/// <summary>
/// امن‌سازیِ JSON برای نشستن داخل یک تگ &lt;script&gt;.
///
/// مسئله: هر دو جای سایت که JSON داخل صفحه چاپ می‌شود (JSON-LD در
/// <c>_JsonLd.cshtml</c> و داده‌ی دمو در <c>Index.cshtml</c>) عمداً از
/// <c>UnsafeRelaxedJsonEscaping</c> استفاده می‌کنند تا متن فارسی به
/// <c>\uXXXX</c> تبدیل نشود و حجم HTML چند برابر نشود. ولی آن انکودر
/// <c>&lt;</c> و <c>&gt;</c> را هم دست‌نخورده می‌گذارد.
///
/// یعنی اگر کسی که به پنل مدیریت دسترسی دارد در هر فیلدی —مثلاً توضیح سایت
/// یا متن یک پیامِ دمو— رشته‌ی <c>&lt;/script&gt;</c> بنویسد، مرورگر همان‌جا
/// تگ را می‌بندد و هرچه بعدش بیاید کدِ صفحه می‌شود. یعنی XSS ماندگار روی
/// همه‌ی بازدیدکننده‌ها.
///
/// راه‌حل استاندارد و کم‌هزینه: <c>&lt;/</c> را به <c>&lt;\/</c> تبدیل کن.
/// <c>\/</c> در JSON یک escape معتبر برای <c>/</c> است، پس مقدارِ parse‌شده
/// دقیقاً همان می‌ماند؛ ولی تحلیل‌گرِ HTML دیگر یک تگِ بسته نمی‌بیند.
/// <c>&lt;!--</c> هم به همین دلیل خنثی می‌شود (شروع کامنتِ HTML).
///
/// چرا جای دیگری این کار لازم نیست: بقیه‌ی صفحه با Razor چاپ می‌شود و Razor
/// خودش HTML-encode می‌کند؛ فقط این دو نقطه <c>Html.Raw</c> دارند.
/// </summary>
public static class JsonForScript
{
    public static string Escape(string json) =>
        json.Replace("</", @"<\/").Replace("<!--", @"<\!--");
}
