namespace Up2Ai.Services;

/// <summary>
/// یک فهرست از رکوردها، جدا از این‌که کجا نگه داشته می‌شود.
///
/// این واسط عمداً کوچک است و دقیقاً همان دو کاری را دارد که انبارهای سایت
/// (لید، نوشته، نظر، کاربر پنل) از روز اول انجام می‌دادند: «همه را بخوان» و
/// «زیر قفل بخوان، عوض کن، بنویس». به همین دلیل مهاجرت از فایل به پستگرس
/// هیچ خطی از منطقِ کسب‌وکار را دست نزد — فقط پیاده‌سازیِ زیرِ همین دو متد
/// عوض شد.
/// </summary>
public interface IRecordStore<T> where T : class
{
    /// <summary>خواندنِ بدون قفل. برای نمایش کافی است.</summary>
    List<T> Read();

    /// <summary>
    /// فهرست را زیر قفل می‌خواند، به <paramref name="body"/> می‌دهد، و اگر آن
    /// تابع <c>true</c> برگرداند نتیجه را می‌نویسد. نوشتنِ مشروط عمدی است:
    /// «حذفِ چیزی که وجود ندارد» نباید چیزی را بازنویسی کند.
    /// </summary>
    Task<TResult> MutateAsync<TResult>(Func<List<T>, (bool Save, TResult Result)> body);
}
